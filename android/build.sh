#!/usr/bin/env bash
# Builds the Puneet Studios Android app into android/dist/PuneetStudios.apk.
# The Phone Sync page offers that file for download (GET /api/sync/app).
#
# Needs the tools from setup-tools.bat (Java 17 + Android SDK in
# %LOCALAPPDATA%\PuneetStudiosBuild). No Gradle: just the plain Android build steps.
#
# Usage (Git Bash):  bash android/build.sh
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
TOOLS="${LOCALAPPDATA//\\//}/PuneetStudiosBuild"
JDK="$(ls -d "$TOOLS"/jdk-17*/ | head -1)"
SDK="$TOOLS/sdk"
BT="$SDK/build-tools/35.0.0"
ANDROID_JAR="$SDK/platforms/android-35/android.jar"
OUT="$HERE/build"
DIST="$HERE/dist"
KEYSTORE="$HERE/release.jks"
# Private values (signing-key password, app-lock PIN hash) live in android/secrets.properties,
# which is never committed. See android/secrets.example.properties.
SECRETS="$HERE/secrets.properties"
[ -f "$SECRETS" ] || { echo "Missing android/secrets.properties (copy secrets.example.properties and fill it in)."; exit 1; }
secret() { grep -E "^$1=" "$SECRETS" | head -1 | cut -d= -f2- | tr -d '\r'; }
PASS="$(secret KEYSTORE_PASSWORD)"
PIN_SHA256="$(secret PIN_SHA256)"

for need in "$JDK/bin/javac.exe" "$BT/aapt2.exe" "$ANDROID_JAR"; do
  [ -e "$need" ] || { echo "Missing $need — run android/setup-tools.bat first."; exit 1; }
done

rm -rf "$OUT" && mkdir -p "$OUT/classes" "$OUT/gen" "$DIST"

# The app's version comes from AndroidManifest.xml: written into BuildInfo.java and
# dist/version.json (the app compares it with the PC's to update itself).
CODE=$(grep -o 'android:versionCode="[0-9]*"' "$HERE/AndroidManifest.xml" | grep -o '[0-9]*')
NAME=$(grep -o 'android:versionName="[^"]*"' "$HERE/AndroidManifest.xml" | sed 's/.*="\(.*\)"/\1/')
cat > "$HERE/src/com/puneetstudios/app/BuildInfo.java" <<JAVA
package com.puneetstudios.app;

// Generated by build.sh from AndroidManifest.xml. Don't edit by hand.
public final class BuildInfo {
    public static final String VERSION = "$NAME";
    public static final int CODE = $CODE;

    private BuildInfo() {}
}
JAVA

cat > "$HERE/src/com/puneetstudios/app/Secrets.java" <<JAVA
package com.puneetstudios.app;

// Generated by build.sh from android/secrets.properties. Not committed.
final class Secrets {
    static final String PIN_SHA256 = "$PIN_SHA256";

    private Secrets() {}
}
JAVA

echo "1/6 Resources"
"$BT/aapt2.exe" compile --dir "$HERE/res" -o "$OUT/res.zip"
"$BT/aapt2.exe" link -o "$OUT/app.unsigned.apk" -I "$ANDROID_JAR" \
  --manifest "$HERE/AndroidManifest.xml" --java "$OUT/gen" "$OUT/res.zip"

echo "2/6 Java"
# The project path has spaces, so pass file lists through a file (quoted, one per line).
find "$HERE/src" "$OUT/gen" -name '*.java' | while read -r f; do echo "\"$(cygpath -m "$f")\""; done > "$OUT/sources.txt"
# Java 8's own library (has what lambdas need) + Android's classes on top.
"$JDK/bin/javac.exe" --release 8 -nowarn -encoding UTF-8 \
  -classpath "$ANDROID_JAR" -d "$OUT/classes" "@$(cygpath -m "$OUT/sources.txt")"

echo "3/6 Dex"
"$JDK/bin/jar.exe" cf "$OUT/classes.jar" -C "$OUT/classes" .
"$JDK/bin/java.exe" -cp "$BT/lib/d8.jar" com.android.tools.r8.D8 --release --min-api 26 \
  --lib "$ANDROID_JAR" --output "$OUT" "$OUT/classes.jar"

echo "4/6 Package"
(cd "$OUT" && "$BT/aapt.exe" add app.unsigned.apk classes.dex >/dev/null)
"$BT/zipalign.exe" -f -p 4 "$OUT/app.unsigned.apk" "$OUT/app.aligned.apk"

echo "5/6 Sign"
if [ ! -f "$KEYSTORE" ]; then
  # Keep this file: phones only accept updates signed with the same key.
  "$JDK/bin/keytool.exe" -genkeypair -keystore "$KEYSTORE" -alias puneet -keyalg RSA -keysize 2048 \
    -validity 20000 -storepass "$PASS" -keypass "$PASS" -dname "CN=Puneet Studios" >/dev/null
fi
"$JDK/bin/java.exe" -jar "$BT/lib/apksigner.jar" sign --ks "$KEYSTORE" --ks-pass "pass:$PASS" \
  --key-pass "pass:$PASS" --out "$DIST/PuneetStudios.apk" "$OUT/app.aligned.apk"

echo "6/6 Check"
"$JDK/bin/java.exe" -jar "$BT/lib/apksigner.jar" verify "$DIST/PuneetStudios.apk"
ls -la "$DIST/PuneetStudios.apk"
printf '{"versionCode":%s,"versionName":"%s","built":%s}\n' "$CODE" "$NAME" "$(date +%s)000" > "$DIST/version.json"
echo "Done: android/dist/PuneetStudios.apk (version $NAME, code $CODE)"
